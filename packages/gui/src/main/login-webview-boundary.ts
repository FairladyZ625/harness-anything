import { randomUUID } from "node:crypto";
import { X509Certificate } from "node:crypto";

/**
 * The one certificate an embedded sign-in may trust: the leaf of the listener configuration the
 * daemon serves, pinned to that listener's full HTTPS origin (`https://hostname:port`) and the
 * SHA-256 fingerprint of the configured certificate file. Everything else — another port on the
 * same host, another host, another certificate, or any request after this sign-in ends — stays
 * under Chromium's own verification and fails closed.
 */
export interface LoginListenerTrust {
  readonly origin: string;
  readonly fingerprint256: string;
}

/**
 * Resolve the trust anchor for one sign-in from the daemon's `listener` reply. Only an
 * authorization URL whose origin is exactly the configured listener origin earns trust: the daemon
 * serves no other HTTPS origin, so a URL anywhere else is not this listener and must not be
 * trusted on its say-so. The certificate file is read at sign-in time, so an operator replacing
 * it takes effect on the next sign-in without a restart.
 */
export function resolveLoginListenerTrust(input: {
  readonly listenerReply: unknown;
  readonly authorizationUrl: string;
  readonly readCertificateFile: (file: string) => string;
}): LoginListenerTrust | null {
  const listener = (input.listenerReply as { readonly listener?: unknown } | null)?.listener;
  if (listener === null || typeof listener !== "object") return null;
  const { hostname, port, certificateFile } = listener as Record<string, unknown>;
  if (typeof hostname !== "string" || typeof certificateFile !== "string") return null;
  if (!Number.isInteger(port) || (port as number) < 1 || (port as number) > 65_535) return null;
  const origin = `https://${hostname.toLowerCase()}:${port}`;
  if (new URL(input.authorizationUrl).origin !== origin) return null;
  // A configured certificate that cannot be read or parsed fails the sign-in with its own error.
  return { origin, fingerprint256: certificateFingerprint256(input.readCertificateFile(certificateFile)) };
}

/** The leaf is the first certificate in the file, which is the certificate the listener serves. */
export function certificateFingerprint256(pem: string): string {
  return new X509Certificate(pem).fingerprint256;
}

/**
 * The login partition contacts exactly two origins: the listener it trusts and the loopback
 * callback the provider's final redirect returns to. A cached certificate acceptance is keyed by
 * hostname only, so a same-host-different-port request would otherwise ride it; this origin
 * membership check cancels such requests before they can reach certificate verification.
 */
export function isAllowedLoginRequest(url: string, allowedOrigins: readonly string[]): boolean {
  try {
    return allowedOrigins.includes(new URL(url).origin);
  } catch {
    return false;
  }
}

export interface LoginWebviewGrantHandle {
  /** Opaque identifier the renderer puts on its webview partition attribute; it names no session. */
  readonly partitionToken: string;
  /** The in-memory partition this one sign-in lives in; generated by the main process, never reused. */
  readonly partition: string;
}

/** What the webview attach policy needs to place a guest into a sign-in's isolated partition. */
export interface LoginWebviewAttachment {
  readonly partition: string;
  readonly allowedOrigins: readonly string[];
}

interface LoginWebviewGrantRecord extends LoginWebviewGrantHandle {
  readonly expectedSrc: string;
  readonly allowedOrigins: readonly string[];
  readonly trust: LoginListenerTrust;
  /** The isolated session this grant owns, matched by identity when a guest attaches. */
  readonly session: object;
  readonly guestWebContentsIds: Set<number>;
}

/**
 * One embedded sign-in over a daemon-configured self-signed HTTPS listener gets one short-lived
 * authorization. The renderer only ever holds the opaque `partitionToken`; the real partition is
 * generated here and handed out at `will-attach-webview` time, only for the exact authorization
 * URL this sign-in began with. `release` — on settle, cancel, failure or webview destruction —
 * kills the token and every certificate decision the grant's guests could still earn. The
 * partition name is never reused, so Chromium's per-session certificate cache cannot carry an
 * acceptance from one sign-in into any later context.
 */
export function createLoginWebviewGrants(
  createIdentifiers: { readonly createToken?: () => string; readonly createPartition?: () => string } = {},
): {
  readonly authorize: (input: {
    readonly expectedSrc: string;
    readonly allowedOrigins: readonly string[];
    readonly trust: LoginListenerTrust;
    /** Isolated session factory: the registry generates the partition name and owns the session it returns. */
    readonly createSession: (partition: string) => object;
  }) => LoginWebviewGrantHandle;
  readonly consumeWebviewAttachment: (params: {
    readonly partition?: string;
    readonly src?: string;
  }) => LoginWebviewAttachment | null;
  readonly bindGuestWebContents: (webContentsId: number, session: object) => LoginWebviewAttachment | null;
  readonly unbindGuestWebContents: (webContentsId: number) => void;
  readonly release: (partitionToken: string) => void;
  readonly decideCertificateError: (input: {
    readonly webContentsId: number;
    readonly url: string;
    readonly certificatePem: string;
  }) => boolean;
} {
  const createToken = createIdentifiers.createToken ?? randomUUID,
    createPartition = createIdentifiers.createPartition ?? (() => `login-${randomUUID()}`),
    grants = new Map<string, LoginWebviewGrantRecord>(),
    attachmentOf = (record: LoginWebviewGrantRecord): LoginWebviewAttachment => ({
      partition: record.partition,
      allowedOrigins: record.allowedOrigins,
    });
  return {
    authorize: ({ expectedSrc, allowedOrigins, trust, createSession }) => {
      const handle: LoginWebviewGrantHandle = { partitionToken: createToken(), partition: createPartition() };
      grants.set(handle.partitionToken, {
        ...handle,
        expectedSrc,
        allowedOrigins,
        trust,
        session: createSession(handle.partition),
        guestWebContentsIds: new Set(),
      });
      return handle;
    },
    consumeWebviewAttachment: (params) => {
      const record = grants.get(String(params.partition));
      // The authorization is bound to the exact initial URL this sign-in began with; anything a
      // renderer offers besides that (or after release) falls through to the default attach denial.
      if (!record || params.src !== record.expectedSrc) return null;
      return attachmentOf(record);
    },
    bindGuestWebContents: (webContentsId, session) => {
      const record = [...grants.values()].find((grant) => grant.session === session);
      if (!record) return null;
      record.guestWebContentsIds.add(webContentsId);
      return attachmentOf(record);
    },
    unbindGuestWebContents: (webContentsId) => {
      for (const record of grants.values()) record.guestWebContentsIds.delete(webContentsId);
    },
    release: (partitionToken) => {
      const record = grants.get(partitionToken);
      grants.delete(partitionToken);
      record?.guestWebContentsIds.clear();
    },
    decideCertificateError: ({ webContentsId, url, certificatePem }) => {
      const record = [...grants.values()].find((grant) => grant.guestWebContentsIds.has(webContentsId));
      if (!record) return false;
      try {
        return (
          new URL(url).origin === record.trust.origin &&
          certificateFingerprint256(certificatePem) === record.trust.fingerprint256
        );
      } catch {
        return false;
      }
    },
  };
}
