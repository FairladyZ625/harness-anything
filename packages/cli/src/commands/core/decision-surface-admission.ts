import {
  type HarnessLayoutInput
} from "@harness-anything/kernel";
import type { CliResult } from "../../cli/types.ts";
import {
  decisionSurfaceCandidateThreshold,
  normalizeDecisionSurfaces,
  searchDecisionSurfaces,
  type DecisionSurfaceAdmissionReport,
  type DecisionSurfaceCandidate
} from "./decision-surface-search.ts";

export interface DecisionSurfaceAdmission {
  readonly requested: boolean;
  readonly report: DecisionSurfaceAdmissionReport;
  readonly warnings: ReadonlyArray<unknown>;
}

export function evaluateDecisionSurfaceAdmission(
  rootInput: HarnessLayoutInput,
  surfaces: ReadonlyArray<string> | undefined
): DecisionSurfaceAdmission {
  const normalized = normalizeDecisionSurfaces(surfaces ?? []);
  if (normalized.length === 0) return emptyAdmission();
  try {
    const report = searchDecisionSurfaces(rootInput, normalized);
    return {
      requested: true,
      report,
      warnings: admissionWarnings(report)
    };
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    const report = {
      schema: "decision-surface-admission/v1",
      threshold: decisionSurfaceCandidateThreshold,
      scannedDecisionCount: 0,
      matches: [],
      candidates: [],
      unavailable: reason
    } satisfies DecisionSurfaceAdmissionReport;
    return {
      requested: true,
      report,
      warnings: [{
        severity: "warning",
        code: "decision_surface_search_unavailable",
        message: `Decision surface search was unavailable and did not block the command: ${reason}`
      }]
    };
  }
}

export function attachDecisionSurfaceAdmission(
  result: CliResult,
  admission: DecisionSurfaceAdmission
): CliResult {
  if (!admission.requested) return result;
  const report = result.report && typeof result.report === "object" && !Array.isArray(result.report)
    ? result.report as Record<string, unknown>
    : {};
  return {
    ...result,
    warnings: [...(result.warnings ?? []), ...admission.warnings],
    report: { ...report, decisionAdmission: admission.report }
  };
}

export function injectDecisionAdmissionReadSet(
  writes: ReadonlyArray<{ readonly path: string; readonly body: string; readonly packageSlug?: string }>,
  input: {
    readonly rootInput: HarnessLayoutInput;
    readonly taskId: string;
    readonly packageSlug?: string;
    readonly surfaces?: ReadonlyArray<string>;
  }
): ReadonlyArray<{ readonly path: string; readonly body: string; readonly packageSlug?: string }> {
  const admission = evaluateDecisionSurfaceAdmission(input.rootInput, input.surfaces);
  if (!admission.requested || writes.some((write) => write.path === "read_set.md")) return writes;
  return [...writes, {
    path: "read_set.md",
    body: renderDecisionAdmissionReadSet(admission.report),
    ...(input.packageSlug ? { packageSlug: input.packageSlug } : {})
  }];
}

export function renderDecisionAdmissionReadSet(report: DecisionSurfaceAdmissionReport): string {
  const lines = [
    "# Decision Admission Read Set",
    "",
    "Generated by `task create` from explicitly declared machine-surface anchors. These are search candidates, not machine judgments.",
    ""
  ];
  if (report.unavailable) {
    lines.push("## Search unavailable", "", `- ${report.unavailable}`, "");
    return lines.join("\n");
  }
  for (const match of report.matches) {
    lines.push(`## Surface \`${match.surface}\``, "");
    if (!match.discriminative) {
      lines.push(`- Non-discriminative: ${match.matchCount} decisions matched (threshold ${report.threshold}); refine this surface before relying on it.`, "");
      continue;
    }
    if (match.candidates.length === 0) {
      lines.push("- No existing decision matched.", "");
      continue;
    }
    lines.push(...match.candidates.map((candidate) =>
      `- \`${candidate.decisionId}\` — ${candidate.title} (${candidate.state}) — \`${candidate.path}\``), "");
  }
  return lines.join("\n");
}

function admissionWarnings(report: DecisionSurfaceAdmissionReport): ReadonlyArray<unknown> {
  return report.matches.map((match) => match.discriminative
    ? {
      severity: "warning",
      code: "decision_surface_candidates",
      surface: match.surface,
      matchCount: match.matchCount,
      candidates: match.candidates,
      message: match.candidates.length === 0
        ? `Decision surface '${match.surface}' matched no existing decisions.`
        : `Decision surface '${match.surface}' matched ${match.matchCount} existing decision(s): ${match.candidates.map(renderCandidate).join("; ")}`
    }
    : {
      severity: "warning",
      code: "decision_surface_not_discriminative",
      surface: match.surface,
      matchCount: match.matchCount,
      threshold: report.threshold,
      candidates: [],
      message: `Decision surface '${match.surface}' is non-discriminative (${match.matchCount} matches; threshold ${report.threshold}); refine it. Candidate details were omitted.`
    });
}

function renderCandidate(candidate: DecisionSurfaceCandidate): string {
  return `${candidate.decisionId} | ${candidate.title} | ${candidate.state}`;
}

function emptyAdmission(): DecisionSurfaceAdmission {
  return {
    requested: false,
    report: {
      schema: "decision-surface-admission/v1",
      threshold: decisionSurfaceCandidateThreshold,
      scannedDecisionCount: 0,
      matches: [],
      candidates: []
    },
    warnings: []
  };
}
